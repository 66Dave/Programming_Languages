import math

x = 25
#square root 
print(math.sqrt(x))
#power
print(math.pow(x,5))
#ceiling
print(math.ceil(3.2))
#floor
print(math.floor(4.9))
#factorial
print(math.factorial(x))
#gcd
print(math.gcd(15,x))
#pi
print (math.pi)
#Euler's constant
print(math.e)
#math.sin(), cos(), tan()
print(math.sin(x),math.cos(x),math.tan(x))
#log
print(math.log(math.e))